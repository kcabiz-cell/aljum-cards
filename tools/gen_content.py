def relation(d, a):
    if d == a: return "동일"
    if (d - a) % 12 == 6: return "충"
    if SIX[d] == a: return "육합"
    if any(d in t and a in t for t in TRI): return "삼합"
    if HAE[d] == a: return "해"
    if PA[d] == a: return "파"
    return "무난"


def years(bi):
    ys = [y for y in range(1950, 2027) if (y - 4) % 12 == bi][-6:]
    return " · ".join(str(y) if (i == 0 or y >= 2000) else f"{y % 100}" for i, y in enumerate(ys))


def build(dt):
    n = (54 + (dt - date(2000, 1, 1)).days) % 60
    s, b = n % 10, n % 12
    ordn = dt.toordinal()
    group = list(range(0, 6)) if (dt - date(2026, 10, 21)).days % 2 == 0 else list(range(6, 12))
    other = [i for i in range(12) if i not in group]
    wd = "월화수목금토일"[dt.weekday()]
    ilgin = S[s] + B[b]; ilgin_ko = KS[s] + KB[b] + "일"
    seen, cards = {}, []
    for i in group:
        r = relation(b, i)
        k = seen.get(r, 0); seen[r] = k + 1
        kw, sm, body, tip = POOL[r][(ordn + k) % len(POOL[r])]
        cards.append(dict(animal=ANI[i], hanja=B[i], color=COLOR[i], years=years(i), keyword=kw,
                          summary=sm, body=body, tip=tip, relation=r))
    se, be = S_EL[s], B_EL[b]
    lines = [f"🔮 오늘은 {ilgin_ko}({ilgin})이에요.",
             f"{KS[s]}({EL_KO[se]}) 기운 위에 {KB[b]}({EL_KO[be]}) 기운이 얹힌 날로, {EL_MOOD[se]} 하루예요.",
             ""]
    for c in cards:
        note = REL_NOTE[c['relation']]
        if c['relation'] == "무난":
            note = ["오늘 기운과 잔잔하게 어우러져 마음이 평온한 날이에요", "오늘 기운과 편안하게 어우러지는 평온한 날이에요",
                    "오늘 기운과 무리 없이 맞아 내 속도대로 가기 좋아요"][(ordn + ANI.index(c['animal'])) % 3]
        lines.append(f"· {c['animal']}띠: {note}")
    lines += ["", "사주는 정해진 답이 아니라 하루를 가볍게 돌아보는 작은 힌트예요.",
              "재미로 보는 운세예요. 선택과 판단은 언제나 나의 몫이에요 🙌",
              f"내일은 {'·'.join(ANI[i] for i in other)}띠 차례예요."]
    first_comment = "\n".join(lines)
    names = "·".join(ANI[i] for i in group)
    names = "·".join(ANI[i] for i in group)
    tags = ("#오늘의운세 #띠별운세 #오늘의띠별운세 " + " ".join(f"#{ANI[i]}띠운세" for i in group) +
            " #사주 #일일운세 #알아줌")
    caption = (f"🔮 오늘의 띠별 운세 ({dt.month}/{dt.day} {wd} · {ilgin_ko})\n"
               f"오늘은 {names}띠의 하루를 살펴봤어요.\n\n"
               + "\n".join(lines[:-3]).rstrip() + "\n\n"
               "옆으로 넘기며 내 띠의 한마디를 확인해 보세요.\n"
               f"나머지 {'·'.join(ANI[i] for i in other)}띠는 내일 만나요 🙌\n\n"
               "사주는 정해진 답이 아니라 하루를 가볍게 돌아보는 작은 힌트예요.\n"
               "재미로 보는 운세예요. 선택과 판단은 언제나 나의 몫이에요.\n\n" + tags)
    for c in cards: c.pop("relation")
    return dict(date=dt.isoformat(), date_label=f"{dt.year}.{dt.month:02d}.{dt.day:02d} ({wd})",
                ilgin=ilgin, ilgin_ko=ilgin_ko, today_title="오늘의 띠별 운세",
                today_animals=[ANI[i] for i in group], tomorrow_animals=[ANI[i] for i in other],
                cards=cards, disclaimer="재미로 보는 오늘의 운세예요. 선택과 판단은 언제나 나의 몫이에요.",
                brand="알아줌", caption=caption, first_comment=first_comment)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    for a in sys.argv[1:]:
        dt = date.fromisoformat(a)
        p = os.path.join(here, f"content_{a}.json")
        json.dump(build(dt), open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
        print("wrote", p)
